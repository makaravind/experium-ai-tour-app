import { describe, it, expect } from 'vitest'
import { buildSeedSql } from '@/tools/export-tour-graph.js'

const node = (id: string, pano_ref: string, over = {}) => ({
  id,
  pano_ref,
  label: `Node ${pano_ref}`,
  lat: 17.5,
  lng: 78.25,
  is_lobby: false,
  tiles_url: `https://x/${pano_ref}/manifest.json`,
  preview_url: `https://x/${pano_ref}/preview.jpg`,
  ...over,
})

const graph = {
  nodes: [
    node('u-37a', '37A'),
    node('u-10', '10'),
    node('u-2', '2'),
    node('u-1', '1', { is_lobby: true, label: 'Park Entrance' }),
  ],
  edges: [
    { from_node_id: 'u-10', to_node_id: 'u-2', bearing: 90, pitch: -15 },
    { from_node_id: 'u-2', to_node_id: 'u-10', bearing: 270, pitch: 0 },
    { from_node_id: 'u-2', to_node_id: 'u-1', bearing: 0, pitch: 3 },
  ],
  exhibits: [
    { code: 9, tour_node_id: 'u-10', tour_heading: 359, tour_pitch: -90 },
    { code: 3, tour_node_id: 'u-2', tour_heading: 0, tour_pitch: 5 },
    { code: 98, tour_node_id: null, tour_heading: null, tour_pitch: null },
  ],
}

const lines = (sql: string, prefix: string) => sql.split('\n').filter((l) => l.startsWith(prefix))

describe('buildSeedSql', () => {
  const sql = buildSeedSql(graph, '2026-11-11')

  it('writes the header with date and counts', () => {
    expect(sql).toContain('GENERATED by tools/export-tour-graph.js from the live DB on 2026-11-11')
    expect(sql).toContain('2026-11-11 - do not edit')
    expect(sql).toContain('4 nodes, 3 edges, 2 exhibit links')
  })

  it('orders nodes by pano_ref numerically (2 < 10 < 37A)', () => {
    const refs = lines(sql, 'INSERT INTO tour_nodes').map((l) => l.match(/VALUES \('([^']+)'/)![1])
    expect(refs).toEqual(['1', '2', '10', '37A'])
  })

  it('orders edges by (from, to) and resolves ids by pano_ref subselect, never UUIDs', () => {
    const edges = lines(sql, 'INSERT INTO tour_edges').map((l) =>
      [...l.matchAll(/pano_ref = '([^']+)'/g)].map((m) => m[1]).join('>')
    )
    expect(edges).toEqual(['2>1', '2>10', '10>2'])
    expect(sql).not.toMatch(/u-\d|u-37a/)
  })

  it('upserts nodes and edges on their natural keys, without any DELETE', () => {
    expect(sql).toContain('ON CONFLICT (pano_ref) DO UPDATE SET label = EXCLUDED.label')
    expect(sql).toContain(
      'ON CONFLICT (from_node_id, to_node_id) DO UPDATE SET bearing = EXCLUDED.bearing, pitch = EXCLUDED.pitch'
    )
    expect(sql).not.toMatch(/^DELETE/m)
  })

  it('updates only linked exhibits, keyed by code and sorted', () => {
    const ex = lines(sql, 'UPDATE exhibits')
    expect(ex).toEqual([
      "UPDATE exhibits SET tour_node_id = (SELECT id FROM tour_nodes WHERE pano_ref = '2'), tour_heading = 0, tour_pitch = 5 WHERE code = 3;",
      "UPDATE exhibits SET tour_node_id = (SELECT id FROM tour_nodes WHERE pano_ref = '10'), tour_heading = 359, tour_pitch = -90 WHERE code = 9;",
    ])
  })

  it('is deterministic regardless of input row order', () => {
    const shuffled = {
      nodes: [...graph.nodes].reverse(),
      edges: [...graph.edges].reverse(),
      exhibits: [...graph.exhibits].reverse(),
    }
    expect(buildSeedSql(shuffled, '2026-11-11')).toBe(sql)
  })

  it('doubles single quotes in labels', () => {
    const out = buildSeedSql(
      { nodes: [node('a', '5', { label: "Ficus' Grove; DROP --" })], edges: [], exhibits: [] },
      'd'
    )
    expect(out).toContain("'Ficus'' Grove; DROP --'")
  })

  it('writes NULL for unplaced lat/lng and true/false for is_lobby', () => {
    const out = buildSeedSql(
      {
        nodes: [node('a', '5', { lat: null, lng: null }), node('b', '6', { is_lobby: true })],
        edges: [],
        exhibits: [],
      },
      'd'
    )
    expect(out).toContain("VALUES ('5', 'Node 5', NULL, NULL, false,")
    expect(out).toContain("VALUES ('6', 'Node 6', 17.5, 78.25, true,")
  })

  it('writes NULL for a null heading/pitch on a linked exhibit', () => {
    const out = buildSeedSql(
      {
        nodes: [node('a', '5')],
        edges: [],
        exhibits: [{ code: 1, tour_node_id: 'a', tour_heading: null, tour_pitch: null }],
      },
      'd'
    )
    expect(out).toContain('tour_heading = NULL, tour_pitch = NULL WHERE code = 1;')
  })

  it('throws on dangling node ids and non-finite numbers', () => {
    expect(() =>
      buildSeedSql(
        { ...graph, edges: [{ from_node_id: 'nope', to_node_id: 'u-1', bearing: 1, pitch: 1 }] },
        'd'
      )
    ).toThrow(/unknown tour_node id nope/)
    expect(() =>
      buildSeedSql({ nodes: [node('a', '5', { lat: NaN })], edges: [], exhibits: [] }, 'd')
    ).toThrow(/finite/)
  })
})
