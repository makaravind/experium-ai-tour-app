/**
 * Exports the authored tour graph (tour_nodes, tour_edges, exhibits' tour_* columns) from the live DB
 * as an idempotent data migration: supabase/migrations/<timestamp>_seed_tour_graph.sql.
 *
 * Usage:
 *   node tools/export-tour-graph.js [--stdout]
 *       --stdout prints the SQL instead of writing the migration file.
 *
 * READ ONLY against Supabase. Prereqs: NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in
 * experium-ai-tour-app/.env.local. Re-running rewrites the existing *_seed_tour_graph.sql in place
 * (same filename); output is deterministic, so an unchanged graph yields a byte-identical file.
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath, pathToFileURL } from 'url'
import { loadEnv } from './tile-panorama.js'

const MIGRATIONS = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase', 'migrations')
const SUFFIX = '_seed_tour_graph.sql'
const NEW_FILE_TIMESTAMP = '20261111000100'
const PAGE_LIMIT = 1000 // PostgREST default max rows; fail loudly rather than export a truncated graph

const byRef = (a, b) => a.localeCompare(b, 'en', { numeric: true }) // '2' < '10' < '37' < '37A'

const str = (s) => `'${String(s).replace(/'/g, "''")}'`
const num = (n) => {
  if (n === null || n === undefined) return 'NULL'
  if (typeof n !== 'number' || !Number.isFinite(n)) throw new Error(`Not a finite number: ${n}`)
  return String(n)
}
const nodeId = (ref) => `(SELECT id FROM tour_nodes WHERE pano_ref = ${str(ref)})`

/**
 * Pure: DB rows in, migration SQL out. Natural keys only: nodes by pano_ref, edges by
 * (from pano_ref, to pano_ref), exhibits by `code`. Unlinked exhibits are omitted.
 * @param {{
 *   nodes: { id: string, pano_ref: string, label: string, lat: number|null, lng: number|null,
 *            is_lobby: boolean, tiles_url: string, preview_url: string }[],
 *   edges: { from_node_id: string, to_node_id: string, bearing: number, pitch: number }[],
 *   exhibits: { code: number, tour_node_id: string|null, tour_heading: number|null, tour_pitch: number|null }[],
 * }} graph
 * @param {string} generatedOn YYYY-MM-DD
 */
export function buildSeedSql({ nodes, edges, exhibits }, generatedOn) {
  const refById = new Map(nodes.map((n) => [n.id, n.pano_ref]))
  const refOf = (id) => {
    const ref = refById.get(id)
    if (ref === undefined) throw new Error(`Row references unknown tour_node id ${id}`)
    return ref
  }

  const nodeRows = [...nodes].sort((a, b) => byRef(a.pano_ref, b.pano_ref))
  const edgeRows = edges
    .map((e) => ({
      from: refOf(e.from_node_id),
      to: refOf(e.to_node_id),
      bearing: e.bearing,
      pitch: e.pitch,
    }))
    .sort((a, b) => byRef(a.from, b.from) || byRef(a.to, b.to))
  const exhibitRows = exhibits
    .filter((x) => x.tour_node_id !== null && x.tour_node_id !== undefined)
    .map((x) => ({
      code: x.code,
      ref: refOf(x.tour_node_id),
      heading: x.tour_heading,
      pitch: x.tour_pitch,
    }))
    .sort((a, b) => a.code - b.code)

  const out = [
    `-- Seed the authored virtual-tour graph (m9b): tour_nodes, tour_edges, exhibits.tour_*`,
    `--`,
    `-- GENERATED by tools/export-tour-graph.js from the live DB on ${generatedOn} - do not edit by hand.`,
    `-- Contents: ${nodeRows.length} nodes, ${edgeRows.length} edges, ${exhibitRows.length} exhibit links.`,
    `-- Regenerate: node tools/export-tour-graph.js   (read-only; rewrites this file in place)`,
    `--`,
    `-- Idempotent: every statement is an upsert / keyed UPDATE, so applying it to a DB that already holds`,
    `-- this data changes nothing, and on a fresh DB it creates the graph. It never deletes: rows absent`,
    `-- from this file (e.g. edges removed later in /admin/tour) are left alone.`,
    `--`,
    `-- Natural keys (row UUIDs differ between databases and are never written here):`,
    `--   tour_nodes  by pano_ref`,
    `--   tour_edges  by (from pano_ref, to pano_ref), ids resolved by subselect`,
    `--   exhibits    by code (SMALLINT UNIQUE, assigned server-side and never edited in /admin; the`,
    `--               display ID section+number is renumberable by the author, so it is not used).`,
    `--               Caveat: code is only stable within one lineage of data (ROW_NUMBER backfill in`,
    `--               20261020120000, then server-assigned). On a DB with different codes these UPDATEs`,
    `--               match other or zero rows; only apply to the production lineage.`,
    `-- Only linked exhibits are listed; unlinked ones keep tour_node_id NULL. The IS DISTINCT FROM guard
--   keeps a re-apply from touching rows (and bumping exhibits.updated_at via trg_exhibits_updated_at).`,
    `-- Lobby: tour_nodes_one_lobby allows a single lobby. If a DB already has a different lobby node`,
    `-- this fails loudly on the lobby upsert rather than silently moving it.`,
    ``,
    `-- 1. nodes`,
  ]

  for (const n of nodeRows) {
    out.push(
      `INSERT INTO tour_nodes (pano_ref, label, lat, lng, is_lobby, tiles_url, preview_url) VALUES (` +
        [
          str(n.pano_ref),
          str(n.label),
          num(n.lat),
          num(n.lng),
          n.is_lobby ? 'true' : 'false',
          str(n.tiles_url),
          str(n.preview_url),
        ].join(', ') +
        `)\n  ON CONFLICT (pano_ref) DO UPDATE SET label = EXCLUDED.label, lat = EXCLUDED.lat, lng = EXCLUDED.lng,\n` +
        `  is_lobby = EXCLUDED.is_lobby, tiles_url = EXCLUDED.tiles_url, preview_url = EXCLUDED.preview_url;`
    )
  }

  out.push('', '-- 2. edges')
  for (const e of edgeRows) {
    out.push(
      `INSERT INTO tour_edges (from_node_id, to_node_id, bearing, pitch) VALUES (${nodeId(e.from)}, ${nodeId(e.to)}, ${num(e.bearing)}, ${num(e.pitch)})\n` +
        `  ON CONFLICT (from_node_id, to_node_id) DO UPDATE SET bearing = EXCLUDED.bearing, pitch = EXCLUDED.pitch;`
    )
  }

  out.push('', '-- 3. exhibit links')
  for (const x of exhibitRows) {
    const target = `${nodeId(x.ref)}, ${num(x.heading)}, ${num(x.pitch)}`
    out.push(
      `UPDATE exhibits SET tour_node_id = ${nodeId(x.ref)}, tour_heading = ${num(x.heading)}, tour_pitch = ${num(x.pitch)}\n` +
        `  WHERE code = ${num(x.code)} AND (tour_node_id, tour_heading, tour_pitch) IS DISTINCT FROM (${target});`
    )
  }

  return out.join('\n') + '\n'
}

async function fetchAll(supabase, table, columns) {
  const { data, error } = await supabase.from(table).select(columns)
  if (error) throw new Error(`Read failed (${table}): ${error.message}`)
  if (data.length >= PAGE_LIMIT)
    throw new Error(`${table}: ${data.length} rows hits the page limit; paginate`)
  return data
}

async function main() {
  const stdout = process.argv.includes('--stdout')
  const env = loadEnv()
  const supabaseUrl = env['NEXT_PUBLIC_SUPABASE_URL']
  const serviceKey = env['SUPABASE_SERVICE_ROLE_KEY']
  if (!supabaseUrl || !serviceKey) {
    console.error('Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY in .env.local')
    process.exit(1)
  }

  const { createClient } = await import('@supabase/supabase-js')
  const supabase = createClient(supabaseUrl, serviceKey, { auth: { persistSession: false } })
  const graph = {
    nodes: await fetchAll(
      supabase,
      'tour_nodes',
      'id, pano_ref, label, lat, lng, is_lobby, tiles_url, preview_url'
    ),
    edges: await fetchAll(supabase, 'tour_edges', 'from_node_id, to_node_id, bearing, pitch'),
    exhibits: await fetchAll(supabase, 'exhibits', 'code, tour_node_id, tour_heading, tour_pitch'),
  }
  const unkeyed = graph.exhibits.filter((x) => x.tour_node_id && x.code == null)
  if (unkeyed.length)
    throw new Error(`${unkeyed.length} linked exhibit(s) have no code; cannot key them`)

  const existing = readdirSync(MIGRATIONS).find((f) => f.endsWith(SUFFIX))
  const path = join(MIGRATIONS, existing ?? `${NEW_FILE_TIMESTAMP}${SUFFIX}`)

  // Keep the existing header date when nothing else changed, so re-runs are byte-identical.
  const today = new Date().toISOString().slice(0, 10)
  const previous = existing && existsSync(path) ? readFileSync(path, 'utf8') : null
  const previousDate = previous?.match(/ on (\d{4}-\d{2}-\d{2}) - do not edit/)?.[1]
  let sql = buildSeedSql(graph, previousDate ?? today)
  if (previous !== null && sql !== previous) sql = buildSeedSql(graph, today)

  if (stdout) {
    process.stdout.write(sql)
    return
  }
  if (sql === previous) {
    console.log(`Unchanged: ${path}`)
    return
  }
  writeFileSync(path, sql)
  console.log(`Wrote ${path} (${graph.nodes.length} nodes, ${graph.edges.length} edges)`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((e) => {
    console.error(e.message)
    process.exit(1)
  })
}
